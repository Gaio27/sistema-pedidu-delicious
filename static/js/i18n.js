let currentLang = localStorage.getItem('celvas_lang') || 'tet';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'tet';
  currentLang = lang;
  localStorage.setItem('celvas_lang', lang);
  document.documentElement.lang = lang;

  // Update dropdown label / flag in navbar
  const langLabel = document.getElementById('current-lang-label');
  if (langLabel) {
    const flags = {
      tet: '🇹🇱 Tetun',
      pt: '🇵🇹 Português',
      en: '🇬🇧 English',
      id: '🇮🇩 Indonesia'
    };
    langLabel.innerHTML = flags[lang] || lang.toUpperCase();
  }

  // Translate all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    } else if (translations['tet'][key]) {
      el.innerHTML = translations['tet'][key];
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    } else if (translations['tet'][key]) {
      el.placeholder = translations['tet'][key];
    }
  });

  // Translate titles/tooltips with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (translations[lang] && translations[lang][key]) {
      el.title = translations[lang][key];
    } else if (translations['tet'][key]) {
      el.title = translations['tet'][key];
    }
  });

  // Notify custom JS controllers about language changes
  try {
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  } catch (e) {
    // Ignore in older browser runtimes
  }
}

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations['tet'] && translations['tet'][key]) {
    return translations['tet'][key];
  }
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
