let currentLang = localStorage.getItem('celvas_lang') || 'tet';

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('celvas_lang', lang);

  // Update dropdown label / flag
  const langLabel = document.getElementById('current-lang-label');
  if (langLabel) {
    const flags = { tet: '🇹🇱 Tetun', pt: '🇵🇹 Português', en: '🇬🇧 English', id: '🇮🇩 Indonesia' };
    langLabel.innerHTML = flags[lang] || lang.toUpperCase();
  }

  // Translate all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || (translations['en'] && translations['en'][key]) || key;
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
